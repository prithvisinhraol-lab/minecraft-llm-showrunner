export class ShowrunnerError extends Error {
  constructor(code, message = code, details = {}) {
    super(message);
    this.name = 'ShowrunnerError';
    this.code = code;
    this.details = details;
  }
}

export function showrunnerError(code, message, details) {
  return new ShowrunnerError(code, message, details);
}
